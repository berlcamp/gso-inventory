SELECT s.office_id, s.item_id, 'opening', s.opening_quantity, s.quantity,
       'Opening balance — FY 2026 Inventory by Office sheet'
FROM gso_inventory.office_stocks s
WHERE s.fiscal_year = 2026
  AND NOT EXISTS (
    SELECT 1 FROM gso_inventory.stock_movements m
    WHERE m.office_id = s.office_id AND m.item_id = s.item_id
      AND m.movement_type = 'opening'
  );
